fn main() {
    let mut art = vec![
        "                                %@.",
        "                       %@.      @@.      .@.",
        "                       .@@      @@.     .@@",
        "                        *@@     @@.     @@.",
        "               @@+       @@@@@@@@@@@@@@%@%      .@@.",
        "                *@@.  .*@@@@.        .+@@@@.. .@@@.",
        "                  @@@@@@.                 @@@@@@.",
        "                   @@@..                   .%@@.",
        "          %@=.   .@@-                        .@@=     .@.",
        "          .-@@@@@@@.                          .@@++@@@@@.",
        "               .@@.                       .     @@@-.",
        "               .@@..                      ...   .@@",
        "               @@... . ..  ........ .............@@..",
        "        .@@@@@@@@.................. .............@%@@@@@@@",
        "        .======@@.. .. .......... ...  .. ... ...@@======:.",
        "=@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@=",
        ".********************************************************************.",
    ];

    let mut text = vec![
        "",
        "",
        "Hello",
        "this is a test",
        "can you see this",
        "it's pretty cool",
        "at least if it works",
    ];

    let height = std::cmp::max(art.len(), text.len());

    text.resize(height, "");
    art.resize(height, "");

    let width = art.iter().map(|s| s.len()).max().unwrap();

    for i in 0..height {
        println!("{:<width$} {}", art[i], text[i])
    }
}
